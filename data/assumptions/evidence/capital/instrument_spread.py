# -*- coding: utf-8 -*-
"""Спред субординированного инструмента к оптовому фондированию (A-K8b, MODEL §4.11) — одно место числа.

Прирост инструментов капитала сверх якоря в нормативе — капитал, в балансе — обязательство дороже обычного оптового
фондирования. Спред считается по купонам действующих бессрочных субординированных инструментов эмитента к ключевой
ставке валюты инструмента на дату установления купона; все три инструмента — в долларах США, поэтому «ключевая» —
верхняя граница ставки ФРС. Книга оптового фондирования клетки стоит ключевую ставку плюс долгосрочный спред книги
(отрицательный), поэтому спред инструмента к оптовому фондированию — надбавка к ключевой минус этот спред.

Инструменты и купоны — отчётность МСФО за 2025 год, примечание 18 (с. 78); балансовая стоимость — на 31.12.2025.
Ставки ФРС — общедоступные решения комитета по открытым рынкам; первички по ним в папке передачи нет, поэтому
надбавка — ОЦЕНКА [В]: перенос долларовой надбавки на рублёвый инструмент — отдельное суждение книги (класс C).

Спред начисляется на ВНЕШНЮЮ долю прироста: купон по внутригрупповым инструментам в прибыли группы исключается.
Внешняя доля — по факту якоря: бессрочные субординированные займы в обязательствах МСФО (все — перед внешними
держателями) к инструментам добавочного капитала банка до вычетов (форма 0409808, строка 30); остальное —
внутригрупповые инструменты (оценка разностью: прямого раскрытия нет). Оба числа — лист моста капитала
(inputs/stage1/ras/bridge_ifrs_to_group_capital.csv, строки A5 и D9).
Модуль читают лист сверки капитала (capital_book.py) и лист вывода на ядре (path/derive_on_engine.py).
"""
from __future__ import annotations

import csv
from pathlib import Path

BRIDGE = Path(__file__).resolve().parent / "inputs" / "stage1" / "ras" / "bridge_ifrs_to_group_capital.csv"
ROW_EXTERNAL, ROW_GROSS = "A5", "D9"   # бессрочные займы МСФО (обязательство); инструменты добавочного капитала банка до вычетов

# (инструмент, балансовая стоимость на 31.12.2025, млрд ₽; купон; ключевая валюты на дату установления купона; пояснение)
INSTRUMENTS = (
    ("бессрочные субординированные облигации 2021 года, 600 млн долл.", 35.615, 0.0600, 0.0025,
     "купон фиксирован при размещении в сентябре 2021 года; право отзыва с 20.12.2026"),
    ("бессрочные субординированные облигации 2017 года, 300 млн долл.", 18.211, 0.1126, 0.0450,
     "купон установлен 15.09.2025; право отзыва с 15.09.2027"),
    ("бессрочный субординированный заём акционера (пришёл с Росбанком)", 11.734, 0.1146, 0.0375,
     "ставка на 31.12.2025; годом раньше 12,3 % при ключевой 4,50 %"),
)
ROUND_PP = 4                      # спред пишется с точностью 0,01 п.п.


def margin_to_key() -> dict:
    """Надбавка купона к ключевой ставке валюты: по инструментам, средняя по балансовой стоимости и простая."""
    rows = [{"name": n, "carrying": c, "coupon": k, "key": r, "margin": round(k - r, 4), "note": note}
            for n, c, k, r, note in INSTRUMENTS]
    total = sum(r["carrying"] for r in rows)
    weighted = sum(r["carrying"] * r["margin"] for r in rows) / total
    simple = sum(r["margin"] for r in rows) / len(rows)
    return {"rows": rows, "carrying_total": round(total, 3), "weighted": round(weighted, ROUND_PP),
            "simple": round(simple, ROUND_PP), "range": [min(r["margin"] for r in rows), max(r["margin"] for r in rows)]}


def external_share(as_of: str) -> dict:
    """Доля внешних инструментов в инструментах добавочного капитала банка на дату `as_of` (ГГГГ-ММ-ДД): бессрочные
    субординированные займы МСФО к инструментам банка до вычетов; на эту долю прироста начисляется спред."""
    with BRIDGE.open(encoding="utf-8", newline="") as fh:
        rows = {r["id"]: r for r in csv.DictReader(fh)}
    if as_of not in rows[ROW_EXTERNAL]:
        raise KeyError(f"лист моста капитала: нет даты {as_of}")
    external, gross = float(rows[ROW_EXTERNAL][as_of]), float(rows[ROW_GROSS][as_of])
    return {"as_of": as_of, "external": external, "bank_instruments_gross": gross, "intragroup": round(gross - external, 3),
            "share": round(external / gross, ROUND_PP), "estimate": True}


def spread_to_wholesale(wholesale_lt_spread: float) -> dict:
    """Спред инструмента к оптовому фондированию: надбавка к ключевой (средняя по балансовой стоимости) минус
    долгосрочный спред книги оптового фондирования к ключевой (`nii.books.wholesale.spread.LT`)."""
    m = margin_to_key()
    return {"margin_to_key": m["weighted"], "wholesale_lt_spread": float(wholesale_lt_spread),
            "to_wholesale": round(m["weighted"] - float(wholesale_lt_spread), ROUND_PP), "instruments": m,
            "estimate": True}
